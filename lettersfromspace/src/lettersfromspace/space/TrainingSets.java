// Letters from Space - English rewrite (2026) of the 2001 ESI neural network lab.
package lettersfromspace.space;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Random;

/**
 * Builds positive and negative training sets for one letter from a set of samples grouped by
 * letter (see {@link FrameLoader#groupByLetter}).
 * <p>
 * In 2001 the students drew 5-10 variants of each of their letters by hand. Here the hand-drawn
 * samples are used when they exist, and extra variants can be generated by flipping a few random
 * pixels, which imitates the noise added to the letters hidden in the video. Every letter gets the
 * same number of noisy copies, however many samples it has: a letter with more examples than the
 * others learns to say "yes" too easily (with 8 copies of each of its 5 samples, the A detector
 * fired on empty sky).
 * <p>
 * The 2001 negatives were the other letters only. But about 98 % of the video is empty sky, and a
 * detector that never saw sky during training has no reason to answer "no" on it: detectors such as
 * A, O and R fired on hundreds of sky frames. {@link #build} therefore also adds frames of random
 * empty sky to the negatives ({@link Options#skyFrames()}; set it to 0 to see the 2001 behaviour).
 */
public final class TrainingSets {

    /** Empty-sky frames have up to this percentage of their pixels lit, like the sky in the video. */
    public static final int SKY_MAX_PERCENT = 50;

    /** The positive and negative examples of one training run, in the order they are presented. */
    public record Sets(List<Frame> positives, List<Frame> negatives) {}

    /**
     * How a training set is made: the samples of the letter plus {@code variants} noisy copies of
     * them (up to {@code noisePercent} percent of the pixels flipped), every sample of the other
     * letters as it is, and {@code skyFrames} frames of random empty sky. When {@code freshNoise} is
     * true, {@link LetterDetector} draws new noisy copies and new sky for every epoch (data
     * augmentation): the network never sees the same noise twice, so it has to learn the letter
     * instead of memorising a few examples.
     */
    public record Options(int variants, int noisePercent, int skyFrames, boolean freshNoise) {

        /** 8 noisy copies with up to 8 % noise (like the letters in the video), 50 frames of sky, new noise every epoch. */
        public static Options defaults() {
            return new Options(8, 8, 50, true);
        }
    }

    private TrainingSets() {}

    /**
     * The samples handed to students, grouped by letter: the master glyph of every letter
     * ({@code allLetters.dat}) plus the hand-drawn A's of {@code letterA.dat} when that file exists.
     */
    public static Map<Character, List<Frame>> loadStudentSamples(Path lettersFolder) throws IOException {
        Map<Character, List<Frame>> samples = FrameLoader.groupByLetter(FrameLoader.load(lettersFolder.resolve("allLetters.dat")));
        Path letterA = lettersFolder.resolve("letterA.dat");
        if (Files.exists(letterA)) {
            List<Frame> as = samples.computeIfAbsent('A', k -> new ArrayList<>());
            for (Frame f : FrameLoader.load(letterA)) {
                f.setLetter('A');
                boolean duplicate = false;
                for (Frame existing : as) {
                    duplicate |= existing.samePixels(f);
                }
                if (!duplicate) {
                    as.add(f);
                }
            }
        }
        return samples;
    }

    /** Positives and negatives for {@code letter} (see {@link Options}): one draw of the noisy copies and the sky. */
    public static Sets build(char letter, Map<Character, List<Frame>> samplesByLetter, Options options, Random random) {
        List<Frame> positives = positives(letter, samplesByLetter, options.variants(), options.noisePercent(), random);
        List<Frame> negatives = negatives(letter, samplesByLetter, 0, 0, random);
        negatives.addAll(emptySky(options.skyFrames(), random));
        return new Sets(positives, negatives);
    }

    /**
     * Positive examples for {@code letter}: every sample of that letter plus {@code variants} noisy
     * copies (up to {@code noisePercent} percent of the pixels flipped), taken from the samples in
     * turn. With one sample that is {@code variants} copies of it; with five, the copies are spread
     * over the five.
     */
    public static List<Frame> positives(char letter, Map<Character, List<Frame>> samplesByLetter,
                                        int variants, int noisePercent, Random random) {
        List<Frame> samples = samplesByLetter.get(letter);
        if (samples == null || samples.isEmpty()) {
            throw new IllegalArgumentException("There are no samples for the letter '" + letter + "'");
        }
        List<Frame> positives = new ArrayList<>(samples);
        for (int i = 0; i < variants; i++) {
            positives.add(Noise.noisyCopy(samples.get(i % samples.size()), noisePercent, random));
        }
        return positives;
    }

    /**
     * Negative examples for {@code letter}: every sample of every other letter, plus
     * {@code variants} noisy copies of each.
     */
    public static List<Frame> negatives(char letter, Map<Character, List<Frame>> samplesByLetter,
                                        int variants, int noisePercent, Random random) {
        List<Frame> negatives = new ArrayList<>();
        for (Map.Entry<Character, List<Frame>> e : samplesByLetter.entrySet()) {
            if (e.getKey() == letter) {
                continue;
            }
            for (Frame sample : e.getValue()) {
                negatives.add(sample);
                for (int i = 0; i < variants; i++) {
                    negatives.add(Noise.noisyCopy(sample, noisePercent, random));
                }
            }
        }
        return negatives;
    }

    /**
     * {@code count} frames of empty sky with random stars (up to {@link #SKY_MAX_PERCENT} percent
     * of the pixels), like the frames between the letters of the video. They have no letter.
     */
    public static List<Frame> emptySky(int count, Random random) {
        List<Frame> sky = new ArrayList<>(Math.max(0, count));
        for (int i = 0; i < count; i++) {
            sky.add(Noise.randomSky(SKY_MAX_PERCENT, random));
        }
        return sky;
    }
}
